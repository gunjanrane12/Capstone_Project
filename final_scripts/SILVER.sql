---CUSTOMERS

CREATE TABLE IF NOT EXISTS SILVER.CUSTOMERS (
 CUSTOMER_ID VARCHAR(50),
 CUSTOMER_NAME VARCHAR(150),
 DATE_OF_BIRTH DATE,
 GENDER VARCHAR(20),
 EMAIL VARCHAR(255),
 PHONE VARCHAR(30),
 ADDRESS_LINE VARCHAR(255),
 CITY VARCHAR(100),
 STATE VARCHAR(100),
 REGION VARCHAR(50),
 OCCUPATION VARCHAR(100),
 CUSTOMER_RISK_CATEGORY VARCHAR(30),
 REGISTRATION_DATE DATE,
 SOURCE_UPDATED_TS TIMESTAMP_TZ,
 _FILE_NAME VARCHAR(500),
 _LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
 _BATCH_ID VARCHAR(100)
);


INSERT INTO SILVER.CUSTOMERS (
    CUSTOMER_ID, CUSTOMER_NAME, DATE_OF_BIRTH, GENDER, EMAIL, PHONE,
    ADDRESS_LINE, CITY, STATE, REGION, OCCUPATION, CUSTOMER_RISK_CATEGORY,
    REGISTRATION_DATE, SOURCE_UPDATED_TS, _FILE_NAME, _LOAD_TS, _BATCH_ID
)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TRY_TO_DATE(LEFT(TRIM(DATE_OF_BIRTH), 10), 'MM/DD/YYYY'),
    GENDER,
    EMAIL,
    PHONE,
    ADDRESS_LINE,
    CITY,
    STATE,
    REGION,
    OCCUPATION,
    CUSTOMER_RISK_CATEGORY,
    TRY_TO_DATE(LEFT(TRIM(REGISTRATION_DATE), 10), 'MM/DD/YYYY'),
    TRY_TO_TIMESTAMP_TZ(TRIM(SOURCE_UPDATED_TS), 'MM/DD/YYYY HH24:MI:SS.FF6'),
    _FILE_NAME,
    _LOAD_TS,
    _BATCH_ID
FROM BRONZE.CUSTOMERS;

SELECT*FROM SILVER.CUSTOMERS;


---INSURANCE PRODUCTS

CREATE TABLE IF NOT EXISTS SILVER.INSURANCE_PRODUCTS (
 PRODUCT_ID VARCHAR(50),
 PRODUCT_NAME VARCHAR(150),
 INSURANCE_TYPE VARCHAR(50),
 COVERAGE_CATEGORY VARCHAR(100),
 MINIMUM_SUM_INSURED NUMBER(18,2),
 MAXIMUM_SUM_INSURED NUMBER(18,2),
 PREMIUM_FREQUENCY VARCHAR(30),
 GRACE_PERIOD_DAYS NUMBER(5,0),
 ACTIVE_FLAG BOOLEAN,
 SOURCE_UPDATED_TS TIMESTAMP_TZ,
 _FILE_NAME VARCHAR(500),
 _LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
 _BATCH_ID VARCHAR(100)
);

INSERT OVERWRITE INTO SILVER.INSURANCE_PRODUCTS
(
    PRODUCT_ID,
    PRODUCT_NAME,
    INSURANCE_TYPE,
    COVERAGE_CATEGORY,
    MINIMUM_SUM_INSURED,
    MAXIMUM_SUM_INSURED,
    PREMIUM_FREQUENCY,
    GRACE_PERIOD_DAYS,
    ACTIVE_FLAG,
    SOURCE_UPDATED_TS,
    _FILE_NAME,
    _LOAD_TS,
    _BATCH_ID
)
SELECT
    PRODUCT_ID::VARCHAR(50),
    PRODUCT_NAME::VARCHAR(150),
    INSURANCE_TYPE::VARCHAR(50),
    COVERAGE_CATEGORY::VARCHAR(100),

    TRY_TO_DECIMAL(MINIMUM_SUM_INSURED,18,2),
    TRY_TO_DECIMAL(MAXIMUM_SUM_INSURED,18,2),

    PREMIUM_FREQUENCY::VARCHAR(30),
    TRY_TO_NUMBER(GRACE_PERIOD_DAYS,5,0),

    CASE
        WHEN UPPER(TRIM(ACTIVE_FLAG)) IN ('TRUE','T','YES','Y','1') THEN TRUE
        WHEN UPPER(TRIM(ACTIVE_FLAG)) IN ('FALSE','F','NO','N','0') THEN FALSE
        ELSE NULL
    END,

    TRY_TO_TIMESTAMP_TZ(TRIM(SOURCE_UPDATED_TS)),

    _FILE_NAME::VARCHAR(500),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    _BATCH_ID::VARCHAR(100)

FROM BRONZE.INSURANCE_PRODUCTS;

SELECT * FROM SILVER.INSURANCE_PRODUCTS;


