---PREMIUM PAYMENTS
CREATE TABLE IF NOT EXISTS SILVER.PREMIUM_PAYMENTS (
 PAYMENT_ID VARCHAR(50),
 POLICY_ID VARCHAR(50),
 PREMIUM_SCHEDULE_ID VARCHAR(50),
 PAYMENT_DATE DATE,
 PAYMENT_AMOUNT NUMBER(18,2),
 PAYMENT_METHOD VARCHAR(50),
 PAYMENT_STATUS VARCHAR(50),
 REFERENCE_NUMBER VARCHAR(100),
 SOURCE_UPDATED_TS TIMESTAMP_TZ,
 _FILE_NAME VARCHAR(500),
 _LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
 _BATCH_ID VARCHAR(100)
);

INSERT OVERWRITE INTO SILVER.PREMIUM_PAYMENTS
(
    PAYMENT_ID,
    POLICY_ID,
    PREMIUM_SCHEDULE_ID,
    PAYMENT_DATE,
    PAYMENT_AMOUNT,
    PAYMENT_METHOD,
    PAYMENT_STATUS,
    REFERENCE_NUMBER,
    SOURCE_UPDATED_TS,
    _FILE_NAME,
    _LOAD_TS,
    _BATCH_ID
)
SELECT
    PAYMENT_ID::VARCHAR(50),
    POLICY_ID::VARCHAR(50),
    PREMIUM_SCHEDULE_ID::VARCHAR(50),

    -- Explicit pattern parsing for PAYMENT_DATE
    COALESCE(
        TRY_TO_TIMESTAMP(TRIM(PAYMENT_DATE), 'MM/DD/YYYY HH24:MI:SS.FF')::DATE,
        TRY_TO_TIMESTAMP(TRIM(PAYMENT_DATE), 'DD/MM/YYYY HH24:MI:SS.FF')::DATE,
        TRY_TO_DATE(LEFT(TRIM(PAYMENT_DATE), 10), 'MM/DD/YYYY'),
        TRY_TO_DATE(LEFT(TRIM(PAYMENT_DATE), 10), 'DD/MM/YYYY'),
        SUBSTR(TRIM(PAYMENT_DATE), 1, 10)::DATE
    ),

    TRY_TO_DECIMAL(PAYMENT_AMOUNT, 18, 2),

    PAYMENT_METHOD::VARCHAR(50),
    PAYMENT_STATUS::VARCHAR(50),
    REFERENCE_NUMBER::VARCHAR(100),

    -- Explicit pattern parsing for SOURCE_UPDATED_TS (with timezone fallback)
    COALESCE(
        TRY_TO_TIMESTAMP_TZ(TRIM(SOURCE_UPDATED_TS), 'MM/DD/YYYY HH24:MI:SS.FF'),
        TRY_TO_TIMESTAMP_TZ(TRIM(SOURCE_UPDATED_TS), 'DD/MM/YYYY HH24:MI:SS.FF'),
        TRY_TO_TIMESTAMP_NTZ(TRIM(SOURCE_UPDATED_TS), 'MM/DD/YYYY HH24:MI:SS.FF')::TIMESTAMP_TZ,
        TRY_TO_TIMESTAMP_NTZ(TRIM(SOURCE_UPDATED_TS), 'DD/MM/YYYY HH24:MI:SS.FF')::TIMESTAMP_TZ,
        -- General fallback if it's standard ISO format
        TRY_TO_TIMESTAMP_TZ(TRIM(SOURCE_UPDATED_TS))
    ),

    _FILE_NAME::VARCHAR(500),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    _BATCH_ID::VARCHAR(100)

FROM BRONZE.PREMIUM_PAYMENTS;

SELECT * FROM SILVER.PREMIUM_PAYMENTS;



--CLAIM SETTLEMENTS
CREATE TABLE IF NOT EXISTS SILVER.CLAIM_SETTLEMENTS (
 SETTLEMENT_ID VARCHAR(50),
 CLAIM_ID VARCHAR(50),
 SETTLEMENT_DATE DATE,
 SETTLEMENT_TYPE VARCHAR(50),
 GROSS_SETTLEMENT_AMOUNT NUMBER(18,2),
 DEDUCTIBLE_AMOUNT NUMBER(18,2),
 RECOVERY_AMOUNT NUMBER(18,2),
 NET_SETTLEMENT_AMOUNT NUMBER(18,2),
 PAYMENT_STATUS VARCHAR(50),
 PAYMENT_REFERENCE VARCHAR(100),
 SOURCE_UPDATED_TS TIMESTAMP_TZ,
 _FILE_NAME VARCHAR(500),
 _FILE_ROW_NUMBER NUMBER(10,0),
 _LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
 _BATCH_ID VARCHAR(100)
);


INSERT OVERWRITE INTO SILVER.CLAIM_SETTLEMENTS
(
    SETTLEMENT_ID,
    CLAIM_ID,
    SETTLEMENT_DATE,
    SETTLEMENT_TYPE,
    GROSS_SETTLEMENT_AMOUNT,
    DEDUCTIBLE_AMOUNT,
    RECOVERY_AMOUNT,
    NET_SETTLEMENT_AMOUNT,
    PAYMENT_STATUS,
    PAYMENT_REFERENCE,
    SOURCE_UPDATED_TS,
    _FILE_NAME,
    _FILE_ROW_NUMBER,
    _LOAD_TS,
    _BATCH_ID
)
SELECT
    SETTLEMENT_ID::VARCHAR(50),
    CLAIM_ID::VARCHAR(50),

    COALESCE(
        TRY_TO_DATE(NULLIF(TRIM(SETTLEMENT_DATE), ''), 'YYYY-MM-DD'),
        TRY_TO_DATE(NULLIF(TRIM(SETTLEMENT_DATE), ''), 'DD-MM-YYYY'),
        TRY_TO_DATE(NULLIF(TRIM(SETTLEMENT_DATE), ''), 'MM/DD/YYYY'),
        TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(SETTLEMENT_DATE), ''), 'YYYY-MM-DD HH24:MI:SS.FF3')::DATE,
        TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(SETTLEMENT_DATE), ''), 'MM/DD/YYYY HH24:MI:SS.FF6')::DATE
    ) AS SETTLEMENT_DATE,

    SETTLEMENT_TYPE::VARCHAR(50),

    TRY_TO_DECIMAL(GROSS_SETTLEMENT_AMOUNT,18,2),
    TRY_TO_DECIMAL(DEDUCTIBLE_AMOUNT,18,2),
    TRY_TO_DECIMAL(RECOVERY_AMOUNT,18,2),
    TRY_TO_DECIMAL(NET_SETTLEMENT_AMOUNT,18,2),

    PAYMENT_STATUS::VARCHAR(50),
    PAYMENT_REFERENCE::VARCHAR(100),

    TRY_TO_TIMESTAMP_TZ(TRIM(SOURCE_UPDATED_TS)),

    _FILE_NAME::VARCHAR(500),
    _FILE_ROW_NUMBER::number(10,0),

    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    _BATCH_ID::VARCHAR(100)

FROM BRONZE.CLAIM_SETTLEMENTS;
SELECT * FROM BRONZE.CLAIM_SETTLEMENTS;

