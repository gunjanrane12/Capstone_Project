INSERT INTO SILVER.FRAUD_CASES (
    FRAUD_CASE_ID,
    CLAIM_ID,
    POLICY_ID,
    CUSTOMER_ID,
    FRAUD_SCORE,
    TRIGGER_REASON,
    INVESTIGATION_START_DATE,
    INVESTIGATION_END_DATE,
    INVESTIGATION_STATUS,
    INVESTIGATION_OUTCOME,
    INVESTIGATOR_ID,
    SOURCE_UPDATED_TS,
    _FILE_NAME,
    _LOAD_TS,
    _BATCH_ID
)
SELECT
    FRAUD_CASE_ID::VARCHAR(50),
    CLAIM_ID::VARCHAR(50),
    POLICY_ID::VARCHAR(50),
    CUSTOMER_ID::VARCHAR(50),
    TRY_CAST(FRAUD_SCORE AS NUMBER(5,2)),
    TRIGGER_REASON::VARCHAR(255),

    COALESCE(
        TRY_TO_TIMESTAMP_NTZ(INVESTIGATION_START_DATE, 'MM/DD/YYYY HH24:MI:SS.FF6'),
        TRY_TO_TIMESTAMP_NTZ(INVESTIGATION_START_DATE, 'YYYY-MM-DD HH24:MI:SS.FF3'),
        TRY_TO_TIMESTAMP_NTZ(INVESTIGATION_START_DATE, 'YYYY-MM-DD HH24:MI:SS')
    )::DATE,

    COALESCE(
        TRY_TO_TIMESTAMP_NTZ(INVESTIGATION_END_DATE, 'MM/DD/YYYY HH24:MI:SS.FF6'),
        TRY_TO_TIMESTAMP_NTZ(INVESTIGATION_END_DATE, 'YYYY-MM-DD HH24:MI:SS.FF3'),
        TRY_TO_TIMESTAMP_NTZ(INVESTIGATION_END_DATE, 'YYYY-MM-DD HH24:MI:SS')
    )::DATE,

    INVESTIGATION_STATUS::VARCHAR(50),
    INVESTIGATION_OUTCOME::VARCHAR(100),
    INVESTIGATOR_ID::VARCHAR(50),

    TRY_TO_TIMESTAMP_TZ(SOURCE_UPDATED_TS),

    _FILE_NAME::VARCHAR(500),
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    _BATCH_ID::VARCHAR(100)

FROM BRONZE.FRAUD_CASES;

