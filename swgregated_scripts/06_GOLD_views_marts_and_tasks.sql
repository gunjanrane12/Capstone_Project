-- 4. DIM_DATE
-- ==========================================

CREATE OR REPLACE SECURE VIEW GOLD.VW_DIM_DATE AS
WITH DATE_GENERATOR AS
(
    SELECT
        DATEADD(
            DAY,
            ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1,
            '2000-01-01'::DATE
        ) AS FULL_DATE
    FROM TABLE(GENERATOR(ROWCOUNT => 36525))
)

SELECT
    TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')) AS DATE_KEY,
    FULL_DATE,
    DAY(FULL_DATE) AS DAY_NUMBER,
    DAYNAME(FULL_DATE) AS DAY_NAME,
    DAYOFWEEK(FULL_DATE) AS DAY_OF_WEEK,
    WEEKOFYEAR(FULL_DATE) AS WEEK_NUMBER,
    MONTH(FULL_DATE) AS MONTH_NUMBER,
    MONTHNAME(FULL_DATE) AS MONTH_NAME,
    QUARTER(FULL_DATE) AS QUARTER_NUMBER,
    YEAR(FULL_DATE) AS YEAR_NUMBER,
    CASE
        WHEN DAYOFWEEKISO(FULL_DATE) IN (6, 7)
        THEN 'WEEKEND'
        ELSE 'WEEKDAY'
    END AS DAY_TYPE
FROM DATE_GENERATOR;


