---MART_POLICY_PORTFOLIO

CREATE OR REPLACE SECURE VIEW GOLD.MART_POLICY_PORTFOLIO AS

WITH PREMIUM AS
(
    SELECT
        POLICY_ID,
        SUM(
            CASE
                WHEN UPPER(PAYMENT_STATUS)
                     IN ('PAID', 'SUCCESS', 'COMPLETED')
                THEN PAYMENT_AMOUNT
                ELSE 0
            END
        ) AS PREMIUM_COLLECTED,
        COUNT(
            CASE
                WHEN UPPER(PAYMENT_STATUS)
                     IN ('PAID', 'SUCCESS', 'COMPLETED')
                THEN 1
            END
        ) AS SUCCESSFUL_PAYMENT_COUNT
    FROM GOLD.VW_FACT_PREMIUM_PAYMENT
    GROUP BY POLICY_ID
),

CLAIMS AS
(
    SELECT
        POLICY_ID,
        COUNT(DISTINCT CLAIM_ID) AS TOTAL_CLAIMS,
        SUM(CLAIM_AMOUNT) AS TOTAL_CLAIM_AMOUNT,
        SUM(APPROVED_AMOUNT) AS TOTAL_APPROVED_AMOUNT
    FROM GOLD.VW_FACT_CLAIM
    GROUP BY POLICY_ID
)

SELECT
    P.POLICY_ID,
    P.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    P.PRODUCT_ID,
    PR.PRODUCT_NAME,
    PR.INSURANCE_TYPE,
    P.AGENT_ID,
    P.POLICY_ISSUE_DATE,
    P.POLICY_START_DATE,
    P.POLICY_EXPIRY_DATE,
    P.POLICY_STATUS,

    CASE
        WHEN UPPER(P.POLICY_STATUS) = 'ACTIVE'
        THEN 1 ELSE 0
    END AS ACTIVE_POLICY_FLAG,

    P.SUM_INSURED,
    P.PREMIUM_AMOUNT,
    P.PREMIUM_FREQUENCY,

    COALESCE(PM.PREMIUM_COLLECTED, 0) AS PREMIUM_COLLECTED,
    COALESCE(PM.SUCCESSFUL_PAYMENT_COUNT, 0) AS SUCCESSFUL_PAYMENT_COUNT,
    COALESCE(CL.TOTAL_CLAIMS, 0) AS TOTAL_CLAIMS,
    COALESCE(CL.TOTAL_CLAIM_AMOUNT, 0) AS TOTAL_CLAIM_AMOUNT,
    COALESCE(CL.TOTAL_APPROVED_AMOUNT, 0) AS TOTAL_APPROVED_AMOUNT,

    CASE
        WHEN COALESCE(PM.PREMIUM_COLLECTED, 0) > 0
        THEN ROUND(
            COALESCE(CL.TOTAL_CLAIM_AMOUNT, 0)
            / PM.PREMIUM_COLLECTED * 100, 2
        )
        ELSE 0
    END AS LOSS_RATIO_PROXY

FROM GOLD.VW_DIM_POLICY P

LEFT JOIN GOLD.VW_DIM_CUSTOMER C
    ON P.CUSTOMER_ID = C.CUSTOMER_ID

LEFT JOIN GOLD.VW_DIM_INSURANCE_PRODUCT PR
    ON P.PRODUCT_ID = PR.PRODUCT_ID

LEFT JOIN PREMIUM PM
    ON P.POLICY_ID = PM.POLICY_ID

LEFT JOIN CLAIMS CL
    ON P.POLICY_ID = CL.POLICY_ID;

---MART_CLAIMS_PERFORMANCE 
CREATE OR REPLACE SECURE VIEW GOLD.MART_CLAIMS_PERFORMANCE AS

WITH SETTLEMENT AS
(
    SELECT
        CLAIM_ID,
        MIN(SETTLEMENT_DATE) AS FIRST_SETTLEMENT_DATE,
        SUM(NET_SETTLEMENT_AMOUNT) AS TOTAL_NET_SETTLEMENT
    FROM GOLD.VW_FACT_CLAIM_SETTLEMENT
    GROUP BY CLAIM_ID
)

SELECT
    DATE_TRUNC('MONTH', C.CLAIM_REGISTRATION_DATE) AS CLAIM_MONTH,
    C.CLAIM_TYPE,
    C.CLAIM_STATUS,

    COUNT(DISTINCT C.CLAIM_ID) AS TOTAL_CLAIMS,
    COUNT(DISTINCT C.POLICY_ID) AS POLICIES_WITH_CLAIMS,

    ROUND(
        COUNT(DISTINCT C.CLAIM_ID)
        / NULLIF(COUNT(DISTINCT C.POLICY_ID), 0),
        2
    ) AS CLAIM_FREQUENCY,

    SUM(C.CLAIM_AMOUNT) AS TOTAL_CLAIM_AMOUNT,
    AVG(C.CLAIM_AMOUNT) AS AVERAGE_CLAIM_AMOUNT,
    SUM(C.APPROVED_AMOUNT) AS TOTAL_APPROVED_AMOUNT,

    ROUND(
        SUM(C.APPROVED_AMOUNT)
        / NULLIF(SUM(C.CLAIM_AMOUNT), 0) * 100,
        2
    ) AS APPROVAL_RATIO,

    COUNT(DISTINCT S.CLAIM_ID) AS SETTLED_CLAIMS,

    AVG(
        DATEDIFF(
            'DAY',
            C.CLAIM_REGISTRATION_DATE,
            S.FIRST_SETTLEMENT_DATE
        )
    ) AS AVG_SETTLEMENT_TURNAROUND_DAYS,

    SUM(COALESCE(S.TOTAL_NET_SETTLEMENT, 0))
        AS TOTAL_NET_SETTLEMENT

FROM GOLD.VW_FACT_CLAIM C

LEFT JOIN SETTLEMENT S
    ON C.CLAIM_ID = S.CLAIM_ID

GROUP BY
    DATE_TRUNC('MONTH', C.CLAIM_REGISTRATION_DATE),
    C.CLAIM_TYPE,
    C.CLAIM_STATUS;

    ---MART_SETTLEMENT_RECONCILATION
    CREATE OR REPLACE SECURE VIEW GOLD.MART_SETTLEMENT_RECONCILIATION AS

SELECT
    S.SETTLEMENT_ID,
    S.CLAIM_ID,

    C.POLICY_ID,
    C.CUSTOMER_ID,

    C.CLAIM_AMOUNT,
    C.APPROVED_AMOUNT,
    C.CLAIM_STATUS,

    S.SETTLEMENT_DATE,
    S.SETTLEMENT_TYPE,

    S.GROSS_SETTLEMENT_AMOUNT,
    S.DEDUCTIBLE_AMOUNT,
    S.RECOVERY_AMOUNT,
    S.NET_SETTLEMENT_AMOUNT,

    (
        S.GROSS_SETTLEMENT_AMOUNT
        - S.DEDUCTIBLE_AMOUNT
        - S.RECOVERY_AMOUNT
    ) AS EXPECTED_NET_SETTLEMENT,

    (
        S.NET_SETTLEMENT_AMOUNT
        -
        (
            S.GROSS_SETTLEMENT_AMOUNT
            - S.DEDUCTIBLE_AMOUNT
            - S.RECOVERY_AMOUNT
        )
    ) AS RECONCILIATION_DIFFERENCE,

    CASE
        WHEN ABS(
            S.NET_SETTLEMENT_AMOUNT
            -
            (
                S.GROSS_SETTLEMENT_AMOUNT
                - S.DEDUCTIBLE_AMOUNT
                - S.RECOVERY_AMOUNT
            )
        ) <= 0.01
        THEN 'MATCHED'
        ELSE 'MISMATCHED'
    END AS RECONCILIATION_STATUS,

    DATEDIFF(
        'DAY',
        C.CLAIM_REGISTRATION_DATE,
        S.SETTLEMENT_DATE
    ) AS SETTLEMENT_TURNAROUND_DAYS,

    S.PAYMENT_STATUS,
    S.PAYMENT_REFERENCE

FROM GOLD.VW_FACT_CLAIM_SETTLEMENT S

LEFT JOIN GOLD.VW_FACT_CLAIM C
    ON S.CLAIM_ID = C.CLAIM_ID;

    ---MART_FRAUD_RISK
    CREATE OR REPLACE SECURE VIEW GOLD.MART_FRAUD_RISK AS

SELECT
    F.FRAUD_CASE_ID,
    F.CLAIM_ID,
    F.POLICY_ID,
    F.CUSTOMER_ID,

    C.CLAIM_TYPE,
    C.CLAIM_AMOUNT,
    C.APPROVED_AMOUNT,
    C.CLAIM_STATUS,

    F.FRAUD_SCORE,

    CASE
        WHEN F.FRAUD_SCORE >= 70 THEN 'HIGH'
        WHEN F.FRAUD_SCORE >= 40 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS FRAUD_RISK_CATEGORY,

    F.TRIGGER_REASON,
    F.INVESTIGATION_START_DATE,
    F.INVESTIGATION_END_DATE,
    F.INVESTIGATION_STATUS,
    F.INVESTIGATION_OUTCOME,
    F.INVESTIGATOR_ID,

    CASE
        WHEN UPPER(F.INVESTIGATION_STATUS) = 'OPEN'
        THEN 1 ELSE 0
    END AS OPEN_INVESTIGATION_FLAG,

    CASE
        WHEN UPPER(F.INVESTIGATION_OUTCOME) = 'CONFIRMED'
        THEN 1 ELSE 0
    END AS CONFIRMED_FRAUD_FLAG,

    DATEDIFF(
        'DAY',
        F.INVESTIGATION_START_DATE,
        F.INVESTIGATION_END_DATE
    ) AS INVESTIGATION_DURATION_DAYS

FROM GOLD.VW_FACT_FRAUD_CASE F

LEFT JOIN GOLD.VW_FACT_CLAIM C
    ON F.CLAIM_ID = C.CLAIM_ID;
    
