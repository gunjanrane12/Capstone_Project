USE ROLE ACCOUNTADMIN;

--- 1 Insurance Analyst — Policy View
CREATE OR REPLACE SECURE VIEW
INSURANCEPOLICY_LIFECYCLE_DB.SECURE_CONSUMPTION.VW_POLICY_ANALYTICS
AS
SELECT
    POLICY_ID,
    CUSTOMER_ID,
    PRODUCT_ID,
    POLICY_START_DATE,
    POLICY_EXPIRY_DATE,
    SUM_INSURED,
    PREMIUM_AMOUNT,
    POLICY_STATUS
FROM INSURANCEPOLICY_LIFECYCLE_DB.SILVER.POLICIES;

---- 2 Insurance Analyst — Premium Payments View
CREATE OR REPLACE SECURE VIEW
INSURANCEPOLICY_LIFECYCLE_DB.SECURE_CONSUMPTION.VW_PREMIUM_ANALYTICS
AS
SELECT
    PAYMENT_ID,
    POLICY_ID,
    PAYMENT_DATE,
    PAYMENT_AMOUNT,
    PAYMENT_METHOD,
    PAYMENT_STATUS
FROM INSURANCEPOLICY_LIFECYCLE_DB.SILVER.PREMIUM_PAYMENTS;

----- 3 Claims Analyst — Claims View
CREATE OR REPLACE SECURE VIEW
INSURANCEPOLICY_LIFECYCLE_DB.SECURE_CONSUMPTION.VW_CLAIMS_ANALYTICS
AS
SELECT
    CLAIM_ID,
    POLICY_ID,
    CUSTOMER_ID,
    CLAIM_REGISTRATION_DATE,
    LOSS_DATE,
    CLAIM_AMOUNT,
    APPROVED_AMOUNT,
    CLAIM_STATUS
FROM INSURANCEPOLICY_LIFECYCLE_DB.SILVER.CLAIMS_SCD2; ---------------------- REVIEW TABLE 


----- 4 Claims Analyst — Settlement View
CREATE OR REPLACE SECURE VIEW
INSURANCEPOLICY_LIFECYCLE_DB.SECURE_CONSUMPTION.VW_SETTLEMENT_ANALYTICS
AS
SELECT
    SETTLEMENT_ID,
    CLAIM_ID,
    SETTLEMENT_DATE,
    GROSS_SETTLEMENT_AMOUNT,
    DEDUCTIBLE_AMOUNT,
    RECOVERY_AMOUNT,
    NET_SETTLEMENT_AMOUNT,
    PAYMENT_STATUS
FROM INSURANCEPOLICY_LIFECYCLE_DB.SILVER.CLAIM_SETTLEMENTS;


---- 5 Fraud Manager — Fraud View
CREATE OR REPLACE SECURE VIEW
INSURANCEPOLICY_LIFECYCLE_DB.SECURE_CONSUMPTION.VW_FRAUD_ANALYTICS
AS
SELECT
    FRAUD_CASE_ID,
    CLAIM_ID,
    POLICY_ID,
    CUSTOMER_ID,
    FRAUD_SCORE,
    TRIGGER_REASON,
    INVESTIGATION_STATUS,
    INVESTIGATION_OUTCOME,
    INVESTIGATOR_ID
FROM INSURANCEPOLICY_LIFECYCLE_DB.SILVER.FRAUD_CASES;

