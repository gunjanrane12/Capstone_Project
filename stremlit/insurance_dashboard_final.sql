-- 6b. MART_FRAUD_RISK: 'CONFIRMED' never matched 'Confirmed Fraud'; 9999-12-31 gave ~2.9M-day durations
CREATE OR REPLACE SECURE VIEW GOLD.MART_FRAUD_RISK AS
SELECT F.FRAUD_CASE_ID, F.CLAIM_ID, F.POLICY_ID, F.CUSTOMER_ID,
       C.CLAIM_TYPE, C.CLAIM_AMOUNT, C.APPROVED_AMOUNT, C.CLAIM_STATUS,
       F.FRAUD_SCORE,
       CASE WHEN F.FRAUD_SCORE >= 70 THEN 'HIGH'
            WHEN F.FRAUD_SCORE >= 40 THEN 'MEDIUM'
            ELSE 'LOW' END                                                    AS FRAUD_RISK_CATEGORY,
       F.TRIGGER_REASON,
       F.INVESTIGATION_START_DATE,
       NULLIF(F.INVESTIGATION_END_DATE, '9999-12-31'::DATE)                  AS INVESTIGATION_END_DATE,
       F.INVESTIGATION_STATUS, F.INVESTIGATION_OUTCOME, F.INVESTIGATOR_ID,
       IFF(NULLIF(F.INVESTIGATION_END_DATE, '9999-12-31'::DATE) IS NULL
           OR UPPER(F.INVESTIGATION_STATUS) = 'OPEN', 1, 0)                  AS OPEN_INVESTIGATION_FLAG,
       IFF(UPPER(F.INVESTIGATION_OUTCOME) LIKE '%CONFIRMED%', 1, 0)          AS CONFIRMED_FRAUD_FLAG,
       DATEDIFF('DAY', F.INVESTIGATION_START_DATE,
                COALESCE(NULLIF(F.INVESTIGATION_END_DATE, '9999-12-31'::DATE),
                         CURRENT_DATE()))                                     AS INVESTIGATION_DURATION_DAYS
FROM GOLD.VW_FACT_FRAUD_CASE F
LEFT JOIN GOLD.VW_FACT_CLAIM C ON F.CLAIM_ID = C.CLAIM_ID;


