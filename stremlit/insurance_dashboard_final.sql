/* -------------------------------------------------------------------------------------
   1. UNDERWRITING DASHBOARD VIEW  (Insurance Analyst)
   ------------------------------------------------------------------------------------- */
CREATE OR REPLACE SECURE VIEW SECURE_CONSUMPTION.VW_UNDERWRITING_DASHBOARD AS
WITH PAY AS (
    SELECT POLICY_ID,
           SUM(IFF(UPPER(PAYMENT_STATUS) = 'PAID', PAYMENT_AMOUNT, 0)) AS PREMIUM_COLLECTED,
           COUNT_IF(UPPER(PAYMENT_STATUS) = 'PAID')                     AS PAID_PAYMENTS,
           COUNT_IF(UPPER(PAYMENT_STATUS) = 'REVERSED')                 AS REVERSED_PAYMENTS
    FROM SILVER.PREMIUM_PAYMENTS
    GROUP BY POLICY_ID
)
SELECT p.POLICY_ID,
       p.CUSTOMER_ID,
       p.PRODUCT_ID,
       pr.PRODUCT_NAME,
       pr.INSURANCE_TYPE,
       pr.COVERAGE_CATEGORY,
       p.AGENT_ID,
       p.POLICY_ISSUE_DATE,
       p.POLICY_START_DATE,
       p.POLICY_EXPIRY_DATE,
       p.SUM_INSURED,
       p.PREMIUM_AMOUNT,
       p.PREMIUM_FREQUENCY,
       p.POLICY_STATUS,
       p.UNDERWRITING_RISK_BAND,
       COALESCE(c.REGION, 'UNKNOWN')        AS REGION,
       c.STATE,
       c.CUSTOMER_RISK_CATEGORY,
       COALESCE(pay.PREMIUM_COLLECTED, 0)   AS PREMIUM_COLLECTED,
       COALESCE(pay.PAID_PAYMENTS, 0)       AS PAID_PAYMENTS,
       COALESCE(pay.REVERSED_PAYMENTS, 0)   AS REVERSED_PAYMENTS
FROM SILVER.POLICIES p
LEFT JOIN SILVER.INSURANCE_PRODUCTS pr ON pr.PRODUCT_ID  = p.PRODUCT_ID
LEFT JOIN SILVER.CUSTOMERS          c  ON c.CUSTOMER_ID  = p.CUSTOMER_ID
LEFT JOIN PAY                       pay ON pay.POLICY_ID = p.POLICY_ID;


/* -------------------------------------------------------------------------------------
   2. CLAIMS DASHBOARD VIEW  (Claims Analyst) - current SCD2 version only
   ------------------------------------------------------------------------------------- */
CREATE OR REPLACE SECURE VIEW SECURE_CONSUMPTION.VW_CLAIMS_DASHBOARD AS
WITH STL AS (
    SELECT CLAIM_ID,
           COUNT(*)                     AS SETTLEMENT_COUNT,
           MIN(SETTLEMENT_DATE)         AS FIRST_SETTLEMENT_DATE,
           SUM(GROSS_SETTLEMENT_AMOUNT) AS GROSS_SETTLED,
           SUM(NET_SETTLEMENT_AMOUNT)   AS NET_SETTLED,
           COUNT_IF(ABS(NET_SETTLEMENT_AMOUNT
                        - (GROSS_SETTLEMENT_AMOUNT
                           - COALESCE(DEDUCTIBLE_AMOUNT, 0)
                           - COALESCE(RECOVERY_AMOUNT, 0))) > 0.01) AS NET_MISMATCH_COUNT
    FROM SILVER.CLAIM_SETTLEMENTS
    GROUP BY CLAIM_ID
)
SELECT c.CLAIM_ID,
       c.POLICY_ID,
       c.CUSTOMER_ID,
       c.CLAIM_REGISTRATION_DATE,
       c.LOSS_DATE,
       c.CLAIM_TYPE,
       c.CLAIM_AMOUNT,
       c.APPROVED_AMOUNT,
       c.CLAIM_STATUS,
       c.BRANCH_ID,
       pr.INSURANCE_TYPE,
       COALESCE(cu.REGION, 'UNKNOWN')                                    AS REGION,
       COALESCE(s.SETTLEMENT_COUNT, 0)                                   AS SETTLEMENT_COUNT,
       s.FIRST_SETTLEMENT_DATE,
       DATEDIFF(day, c.CLAIM_REGISTRATION_DATE, s.FIRST_SETTLEMENT_DATE) AS SETTLEMENT_TAT_DAYS,
       COALESCE(s.GROSS_SETTLED, 0)                                      AS GROSS_SETTLED,
       COALESCE(s.NET_SETTLED, 0)                                        AS NET_SETTLED,
       COALESCE(s.NET_MISMATCH_COUNT, 0)                                 AS NET_MISMATCH_COUNT
FROM SILVER.CLAIMS_SCD2 c
LEFT JOIN SILVER.POLICIES           p  ON p.POLICY_ID    = c.POLICY_ID
LEFT JOIN SILVER.INSURANCE_PRODUCTS pr ON pr.PRODUCT_ID  = p.PRODUCT_ID
LEFT JOIN SILVER.CUSTOMERS          cu ON cu.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN STL                       s  ON s.CLAIM_ID     = c.CLAIM_ID
WHERE c.IS_CURRENT = TRUE
  AND c.IS_DELETED = FALSE;


