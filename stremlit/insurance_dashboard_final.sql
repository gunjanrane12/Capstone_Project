/* -------------------------------------------------------------------------------------
   5. KPI SUMMARY VIEW  (all roles) - the 10 business KPIs, aggregated per region, no PII
      Stores numerators/denominators so ratios stay correct for any region mix.
   ------------------------------------------------------------------------------------- */
CREATE OR REPLACE SECURE VIEW SECURE_CONSUMPTION.VW_KPI_SUMMARY AS
WITH CUST AS (
    SELECT CUSTOMER_ID, COALESCE(REGION, 'UNKNOWN') AS REGION
    FROM SILVER.CUSTOMERS
),
CLM_CUR AS (
    SELECT CLAIM_ID, POLICY_ID, CUSTOMER_ID, CLAIM_REGISTRATION_DATE, CLAIM_AMOUNT, CLAIM_STATUS
    FROM SILVER.CLAIMS_SCD2
    WHERE IS_CURRENT = TRUE AND IS_DELETED = FALSE
),
POL AS (
    SELECT c.REGION,
           COUNT(*)                                                      AS TOTAL_POLICIES,
           COUNT_IF(UPPER(p.POLICY_STATUS) = 'ACTIVE')                   AS ACTIVE_POLICIES,
           SUM(IFF(UPPER(p.POLICY_STATUS) = 'ACTIVE', p.SUM_INSURED, 0)) AS ACTIVE_SUM_INSURED
    FROM SILVER.POLICIES p
    JOIN CUST c ON c.CUSTOMER_ID = p.CUSTOMER_ID
    GROUP BY c.REGION
),
PAY AS (
    SELECT c.REGION,
           SUM(IFF(UPPER(pp.PAYMENT_STATUS) = 'PAID', pp.PAYMENT_AMOUNT, 0)) AS PREMIUM_COLLECTED
    FROM SILVER.PREMIUM_PAYMENTS pp
    JOIN SILVER.POLICIES p ON p.POLICY_ID   = pp.POLICY_ID
    JOIN CUST c            ON c.CUSTOMER_ID = p.CUSTOMER_ID
    GROUP BY c.REGION
),
STL_CLAIM AS (
    SELECT CLAIM_ID,
           MIN(SETTLEMENT_DATE)       AS FIRST_SETTLEMENT_DATE,
           SUM(NET_SETTLEMENT_AMOUNT) AS NET_SETTLED
    FROM SILVER.CLAIM_SETTLEMENTS
    GROUP BY CLAIM_ID
),
CLM AS (
    SELECT c.REGION,
           COUNT(*)                                                    AS TOTAL_CLAIMS,
           SUM(cl.CLAIM_AMOUNT)                                        AS TOTAL_CLAIM_AMOUNT,
           COUNT_IF(UPPER(cl.CLAIM_STATUS) IN ('APPROVED', 'SETTLED')) AS APPROVED_CLAIMS,
           COUNT(s.CLAIM_ID)                                           AS SETTLED_CLAIMS,
           SUM(DATEDIFF(day, cl.CLAIM_REGISTRATION_DATE, s.FIRST_SETTLEMENT_DATE)) AS TAT_DAYS_SUM,
           SUM(COALESCE(s.NET_SETTLED, 0))                             AS NET_SETTLEMENT_AMOUNT
    FROM CLM_CUR cl
    JOIN CUST c           ON c.CUSTOMER_ID = cl.CUSTOMER_ID
    LEFT JOIN STL_CLAIM s ON s.CLAIM_ID    = cl.CLAIM_ID
    GROUP BY c.REGION
),
FRD AS (
    SELECT c.REGION,
           COUNT(*)                                                     AS FRAUD_CASES,
           COUNT_IF(NULLIF(f.INVESTIGATION_END_DATE, '9999-12-31'::DATE) IS NULL
                    OR UPPER(f.INVESTIGATION_STATUS) = 'OPEN')          AS OPEN_INVESTIGATIONS,
           COUNT_IF(UPPER(f.INVESTIGATION_OUTCOME) LIKE '%CONFIRMED%')  AS CONFIRMED_FRAUD_CASES
    FROM SILVER.FRAUD_CASES f
    JOIN CUST c ON c.CUSTOMER_ID = f.CUSTOMER_ID
    GROUP BY c.REGION
),
RSK AS (
    SELECT c.REGION,
           COUNT_IF(UPPER(r.RISK_CATEGORY) = 'HIGH') AS HIGH_RISK_CLAIMS
    FROM GOLD.FRAUD_RISK_SCORES r
    JOIN CLM_CUR cl ON cl.CLAIM_ID   = r.CLAIM_ID
    JOIN CUST c     ON c.CUSTOMER_ID = cl.CUSTOMER_ID
    GROUP BY c.REGION
),
ALL_REGIONS AS (
    SELECT REGION FROM POL
    UNION SELECT REGION FROM CLM
    UNION SELECT REGION FROM FRD
)
SELECT a.REGION,
       COALESCE(pol.TOTAL_POLICIES, 0)        AS TOTAL_POLICIES,
       COALESCE(pol.ACTIVE_POLICIES, 0)       AS ACTIVE_POLICIES,
       COALESCE(pol.ACTIVE_SUM_INSURED, 0)    AS ACTIVE_SUM_INSURED,
       COALESCE(pay.PREMIUM_COLLECTED, 0)     AS PREMIUM_COLLECTED,
       COALESCE(clm.TOTAL_CLAIMS, 0)          AS TOTAL_CLAIMS,
       COALESCE(clm.TOTAL_CLAIM_AMOUNT, 0)    AS TOTAL_CLAIM_AMOUNT,
       COALESCE(clm.APPROVED_CLAIMS, 0)       AS APPROVED_CLAIMS,
       COALESCE(clm.SETTLED_CLAIMS, 0)        AS SETTLED_CLAIMS,
       COALESCE(clm.TAT_DAYS_SUM, 0)          AS TAT_DAYS_SUM,
       COALESCE(clm.NET_SETTLEMENT_AMOUNT, 0) AS NET_SETTLEMENT_AMOUNT,
       COALESCE(frd.FRAUD_CASES, 0)           AS FRAUD_CASES,
       COALESCE(frd.OPEN_INVESTIGATIONS, 0)   AS OPEN_INVESTIGATIONS,
       COALESCE(frd.CONFIRMED_FRAUD_CASES, 0) AS CONFIRMED_FRAUD_CASES,
       COALESCE(rsk.HIGH_RISK_CLAIMS, 0)      AS HIGH_RISK_CLAIMS
FROM ALL_REGIONS a
LEFT JOIN POL pol ON pol.REGION = a.REGION
LEFT JOIN PAY pay ON pay.REGION = a.REGION
LEFT JOIN CLM clm ON clm.REGION = a.REGION
LEFT JOIN FRD frd ON frd.REGION = a.REGION
LEFT JOIN RSK rsk ON rsk.REGION = a.REGION;


